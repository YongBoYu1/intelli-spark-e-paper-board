def _draw_mask_icon(draw: ImageDraw.ImageDraw, x: int, y: int, size: int, color, rows: tuple[str, ...]) -> None:
    s = max(14, int(size))
    mask = Image.new("1", (16, 16), 0)
    pix = mask.load()
    for yy, row in enumerate(rows[:16]):
        for xx, ch in enumerate(row[:16]):
            if ch == "#":
                pix[xx, yy] = 1
    if s != 16:
        mask = mask.resize((s, s), Image.NEAREST)
    draw.bitmap((int(x), int(y)), mask, fill=color)


def normalize_mic_style(style: str) -> str:
    key = str(style or "").strip().lower()
    key = MIC_STYLE_ALIASES.get(key, key)
    if key not in MIC_ICON_MASKS_16:
        return "tabler_outline"
    return key


def draw_mic_icon(draw: ImageDraw.ImageDraw, x: int, y: int, size: int, color, *, style: str = "tabler_outline") -> None:
    key = normalize_mic_style(style)
    rows = MIC_ICON_MASKS_16.get(key) or MIC_ICON_MASKS_16["tabler_outline"]
    _draw_mask_icon(draw, x, y, size, color, rows)
